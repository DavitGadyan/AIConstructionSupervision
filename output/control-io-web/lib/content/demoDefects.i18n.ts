const texts: Record<Exclude<Locale, "en">, Record<IssueId, IssueText>> = { hy, ru };

/** Returns the issue with title/detail/citation in the requested locale (falls back to English per field). */
export function localizeIssue(issue: DemoIssue, locale: Locale): DemoIssue {
  if (locale === "en") return issue;
  const t = texts[locale][issue.id as IssueId];
  if (!t) return issue;
  return { ...issue, title: t.title, detail: t.detail, citation: issue.citation ? (t.citation ?? issue.citation) : undefined };
}
